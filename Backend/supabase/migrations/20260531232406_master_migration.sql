    SELECT player_name INTO v_name
    FROM drivers.members
    WHERE player_tag = p_player_tag
      AND is_active = true
    LIMIT 1;

    IF v_name IS NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error',   'Player is not an active clan member.'
        );
    END IF;

