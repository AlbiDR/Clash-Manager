        player_tag,
        player_name,
        manual_voyage_crowns,
        manual_voyage_crowns_at,
        total_voyage_crowns,
        percentage_voyage_crowns
    )
    VALUES (
        v_id,
        p_player_tag,
        v_name,
        p_crowns,
        v_now,
        p_crowns,
        LEAST(ROUND((p_crowns::numeric / NULLIF(v_target, 0)::numeric) * 100, 2), 100.0)
    )
    ON CONFLICT (voyage_id, player_tag) DO UPDATE
    SET
        manual_voyage_crowns    = EXCLUDED.manual_voyage_crowns,
        manual_voyage_crowns_at = EXCLUDED.manual_voyage_crowns_at,
        total_voyage_crowns     = EXCLUDED.total_voyage_crowns,
        percentage_voyage_crowns = EXCLUDED.percentage_voyage_crowns,
        updated_at               = v_now;

    PERFORM drivers.refresh_voyage_contributions();

    RETURN jsonb_build_object(
        'success',             true,
        'voyage_id',           v_id,
        'player_tag',          p_player_tag,
        'manual_voyage_crowns', p_crowns
    );
EXCEPTION WHEN OTHERS THEN
    RETURN jsonb_build_object('success', false, 'error', SQLERRM);
END;
$function$;

CREATE OR REPLACE FUNCTION drivers.on_battle_recorded()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_id      BIGINT;
    v_target  INT;
    v_current INT;
    v_end     TIMESTAMPTZ;
    v_name    TEXT;
    v_earned  INT;
BEGIN
    SELECT v.id, v.target_crowns, v.end_at
    INTO v_id, v_target, v_end
    FROM drivers.clan_voyage v
    WHERE v.status = 'ACTIVE'
    AND v.start_at <= NEW.battle_time
    AND v.end_at >= NEW.battle_time
    LIMIT 1;

    IF v_id IS NOT NULL THEN
        SELECT player_name INTO v_name
        FROM drivers.members
        WHERE player_tag = NEW.player_tag
          AND is_active = true
        LIMIT 1;

        IF v_name IS NOT NULL THEN
            v_earned := NEW.team_crowns + (3 - NEW.opponent_crowns);

            INSERT INTO drivers.clan_voyage_contributions (
                voyage_id,
                player_tag,
                player_name,
                total_voyage_crowns,
                percentage_voyage_crowns
            )
            VALUES (
                v_id,
                NEW.player_tag,
                v_name,
                v_earned,
                LEAST(ROUND((v_earned::numeric / NULLIF(v_target, 0)::numeric) * 100, 2), 100.0)
            )
            ON CONFLICT (voyage_id, player_tag)
            DO UPDATE SET
                total_voyage_crowns = drivers.clan_voyage_contributions.total_voyage_crowns + EXCLUDED.total_voyage_crowns,
                percentage_voyage_crowns = LEAST(ROUND(((drivers.clan_voyage_contributions.total_voyage_crowns + EXCLUDED.total_voyage_crowns)::numeric / NULLIF(v_target, 0)::numeric) * 100, 2), 100.0),
                player_name = v_name,
                updated_at = now();
        END IF;

        SELECT SUM(total_voyage_crowns) INTO v_current
        FROM drivers.clan_voyage_contributions
        WHERE voyage_id = v_id;

        IF v_current >= v_target OR now() >= v_end THEN
            INSERT INTO drivers.clan_voyage_contributions (
                voyage_id,
                player_tag,
                player_name,
                total_voyage_crowns,
                percentage_voyage_crowns
            )
            SELECT
                v_id,
                m.player_tag,
                m.player_name,
                0,
                0.0
            FROM drivers.members m
            WHERE m.is_active = true
              AND m.player_tag NOT IN (
                  SELECT player_tag FROM drivers.clan_voyage_contributions WHERE voyage_id = v_id
              )
            ON CONFLICT (voyage_id, player_tag) DO NOTHING;

            UPDATE drivers.clan_voyage
            SET status = 'COMPLETED',
                updated_at = now()
            WHERE id = v_id;
        END IF;
    ELSE
        PERFORM substrate.finalize_expired_voyages();
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION drivers.refresh_voyage_contributions()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_id         BIGINT;
    v_start      TIMESTAMPTZ;
    v_end        TIMESTAMPTZ;
    v_target     INTEGER;
    v_window_end TIMESTAMPTZ;
BEGIN
    SELECT id, start_at, end_at, target_crowns
    INTO v_id, v_start, v_end, v_target
    FROM drivers.clan_voyage
    WHERE status = 'ACTIVE'
    ORDER BY created_at DESC
    LIMIT 1;

    IF v_id IS NULL THEN RETURN; END IF;

    v_window_end := COALESCE(v_end, now());

    -- 1. Strict Pruning: Remove any contribution records for players who are not currently active clan members
    DELETE FROM drivers.clan_voyage_contributions
    WHERE voyage_id = v_id
      AND player_tag NOT IN (SELECT player_tag FROM drivers.members WHERE is_active = true);

    -- 2. Calculate and update the correct live scores.
    UPDATE drivers.clan_voyage_contributions c
    SET
        total_voyage_crowns = COALESCE(c.manual_voyage_crowns, 0) + COALESCE((
            SELECT SUM(b.team_crowns + (3 - b.opponent_crowns))
            FROM drivers.player_battles b
            WHERE b.player_tag = c.player_tag
              AND b.battle_time <= v_window_end
              AND b.battle_type IN ('PvP', 'pathOfLegend', 'riverRacePvP', 'riverRaceDuel', 'trail')
              AND (
                  (c.manual_voyage_crowns IS NOT NULL AND b.battle_time > c.manual_voyage_crowns_at)
                  OR
                  (c.manual_voyage_crowns IS NULL AND b.battle_time >= v_start)
              )
        ), 0),
        updated_at = now()
    WHERE c.voyage_id = v_id;

    -- 3. Final pass: ensure all percentages are accurate.
    UPDATE drivers.clan_voyage_contributions
    SET percentage_voyage_crowns = LEAST(ROUND((total_voyage_crowns::numeric / NULLIF(v_target, 0)::numeric) * 100, 2), 100.0)
    WHERE voyage_id = v_id;

END;
$function$;

CREATE OR REPLACE FUNCTION drivers.log_recruit_event()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_delta NUMERIC;
BEGIN
    IF (TG_OP = 'INSERT') THEN
        INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, new_score, description)
        VALUES (NEW.player_tag, NEW.player_name, 'DISCOVERED', NEW.raw_potential_score, 'Initial discovery via sensory mesh.');

        IF (NEW.status = 'ACTIVE') THEN
            INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, description)
            VALUES (NEW.player_tag, NEW.player_name, 'PROMOTED', 'Direct entry into ACTIVE status.');
        END IF;
        RETURN NEW;
    END IF;

    IF (TG_OP = 'UPDATE') THEN
        IF (NEW.status <> OLD.status) THEN
            IF (NEW.status = 'ACTIVE') THEN
                INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, description)
                VALUES (NEW.player_tag, NEW.player_name, 'PROMOTED', 'Promoted to ACTIVE rotation.');
            ELSIF (OLD.status = 'ACTIVE' AND NEW.status = 'BENCHED') THEN
                INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, description)
                VALUES (NEW.player_tag, NEW.player_name, 'BENCHED', 'Rotated out of ACTIVE status to BENCHED.');
            ELSIF (OLD.status = 'ACTIVE' AND NEW.status = 'QUEUE') THEN
                INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, description)
                VALUES (NEW.player_tag, NEW.player_name, 'ROTATED_OUT', 'Moved from ACTIVE back to QUEUE.');
            ELSIF (NEW.status = 'ARCHIVED') THEN
                INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, description)
                VALUES (NEW.player_tag, NEW.player_name, 'ARCHIVED', 'Recruit archived/retired.');
            END IF;
        END IF;

        IF (NEW.raw_potential_score <> OLD.raw_potential_score) THEN
            v_delta := ABS(NEW.raw_potential_score - OLD.raw_potential_score) / NULLIF(OLD.raw_potential_score, 0);
            IF (v_delta >= 0.05 OR (OLD.raw_potential_score = 0 AND NEW.raw_potential_score > 0)) THEN
                INSERT INTO drivers.recruit_ledger (player_tag, player_name, event_type, old_score, new_score, description)
                VALUES (
                    NEW.player_tag, NEW.player_name, 'SCORE_THRESHOLD_HIT',
                    OLD.raw_potential_score, NEW.raw_potential_score,
                    'Significant performance shift detected (' || ROUND(v_delta * 100, 1) || '% change).'
                );
            END IF;
        END IF;
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$function$;

