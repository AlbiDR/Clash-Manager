    -- Upsert into blacklist
    INSERT INTO drivers.recruit_blacklist (player_tag, player_name, raw_potential_score, reason, expires_at)
    SELECT 
        (val->>'id')::TEXT, 
        (val->>'name')::TEXT, 
        (val->>'raw_potential_score')::NUMERIC, 
