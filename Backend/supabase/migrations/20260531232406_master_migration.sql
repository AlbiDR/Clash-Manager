CREATE OR REPLACE FUNCTION drivers.get_rolling_voyage_performance(p_tag text)
 RETURNS numeric
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
BEGIN
    RETURN (
        SELECT COALESCE(AVG(pct), 0)
        FROM (
            SELECT pct
            FROM (
                -- Source A: individual rows still present in the contributions table.
                SELECT
                    percentage_voyage_crowns                             AS pct,
                    voyage_id                                            AS sort_key
                FROM drivers.clan_voyage_contributions
                WHERE player_tag = p_tag

                UNION ALL

                -- Source B: entries parsed from the archived history string.
                -- Percentage is derived from the stored crowns and target fields.
                SELECT
                    LEAST(
                        ROUND(
                            (regexp_split_to_array(entry, '\|'))[2]::numeric
                            / NULLIF((regexp_split_to_array(entry, '\|'))[3]::numeric, 0)
                            * 100,
                            2
                        ),
                        100.0
                    )                                                    AS pct,
                    (regexp_split_to_array(entry, '\|'))[1]::bigint      AS sort_key
                FROM   drivers.player_voyage_history pvh
                CROSS  JOIN LATERAL unnest(string_to_array(pvh.history, ',')) AS entry
                WHERE  pvh.player_tag = p_tag
                  AND  pvh.history   <> ''
            ) all_voyages
            ORDER BY sort_key DESC
            LIMIT 3
        ) top3
    );
END;
$function$;

CREATE OR REPLACE FUNCTION drivers.on_contribution_manual_override_updated()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_start      TIMESTAMPTZ;
    v_end        TIMESTAMPTZ;
    v_target     INTEGER;
    v_window_end TIMESTAMPTZ;
BEGIN
    IF NEW.manual_voyage_crowns IS DISTINCT FROM OLD.manual_voyage_crowns THEN
        IF NEW.manual_voyage_crowns IS NOT NULL THEN
            NEW.manual_voyage_crowns_at := now();
        ELSE
            NEW.manual_voyage_crowns_at := NULL;
        END IF;

        SELECT start_at, end_at, target_crowns
        INTO v_start, v_end, v_target
        FROM drivers.clan_voyage
        WHERE id = NEW.voyage_id;

        v_window_end := COALESCE(v_end, now());

        NEW.total_voyage_crowns := COALESCE(NEW.manual_voyage_crowns, 0) + COALESCE((
            SELECT SUM(b.team_crowns + (3 - b.opponent_crowns))
            FROM drivers.player_battles b
            WHERE b.player_tag = NEW.player_tag
              AND b.battle_time <= v_window_end
              AND b.battle_type IN ('PvP', 'pathOfLegend', 'riverRacePvP', 'riverRaceDuel', 'trail')
              AND (
                  (NEW.manual_voyage_crowns IS NOT NULL AND b.battle_time > NEW.manual_voyage_crowns_at)
                  OR
                  (NEW.manual_voyage_crowns IS NULL AND b.battle_time >= v_start)
              )
        ), 0);

        NEW.percentage_voyage_crowns := LEAST(ROUND((NEW.total_voyage_crowns::numeric / NULLIF(v_target, 0)::numeric) * 100, 2), 100.0);
        NEW.updated_at := now();
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION drivers.initialize_voyage(target_crowns integer, start_at timestamp with time zone, end_at timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_id BIGINT;
    v_clan_tag TEXT;
BEGIN
    SELECT id INTO v_id FROM drivers.clan_voyage WHERE status = 'ACTIVE' LIMIT 1;

    IF v_id IS NOT NULL THEN
        -- If an event is already active, update target crowns and end_at. 
        -- We ignore start_at to protect the pipeline's original start date.
        UPDATE drivers.clan_voyage 
        SET target_crowns = initialize_voyage.target_crowns,
            end_at = initialize_voyage.end_at
        WHERE id = v_id;
        
        -- Force a refresh so the percentages recalculate immediately against the new target
        PERFORM drivers.refresh_voyage_contributions();

        RETURN jsonb_build_object('success', true, 'voyage_id', v_id, 'message', 'Voyage target and end time updated');
    END IF;

    -- Fetch the authoritative clan tag
    SELECT clan_tag INTO v_clan_tag FROM drivers.clans LIMIT 1;

    IF v_clan_tag IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'No clan found in drivers.clans');
    END IF;

    -- Insert new voyage
    INSERT INTO drivers.clan_voyage (clan_tag, target_crowns, start_at, end_at, status)
    VALUES (v_clan_tag, target_crowns, start_at, end_at, 'ACTIVE')
    RETURNING id INTO v_id;

    RETURN jsonb_build_object('success', true, 'voyage_id', v_id);
EXCEPTION WHEN OTHERS THEN
    RETURN jsonb_build_object('success', false, 'error', SQLERRM);
END;
$function$;

CREATE OR REPLACE FUNCTION drivers.sync_exclusion_cache()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
BEGIN
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        INSERT INTO drivers.exclusion_cache (player_tag)
        VALUES (NEW.player_tag)
        ON CONFLICT (player_tag) DO NOTHING;
    ELSIF TG_OP = 'DELETE' THEN
        IF TG_TABLE_NAME = 'members' THEN
            IF NOT EXISTS (SELECT 1 FROM drivers.recruit_blacklist WHERE player_tag = OLD.player_tag) THEN
                DELETE FROM drivers.exclusion_cache WHERE player_tag = OLD.player_tag;
            END IF;
        ELSIF TG_TABLE_NAME = 'recruit_blacklist' THEN
            IF NOT EXISTS (SELECT 1 FROM drivers.members WHERE player_tag = OLD.player_tag) THEN
                DELETE FROM drivers.exclusion_cache WHERE player_tag = OLD.player_tag;
            END IF;
        END IF;
    END IF;
    RETURN NULL;
END;
$function$;

