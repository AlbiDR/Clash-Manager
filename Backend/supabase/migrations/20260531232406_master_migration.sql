CREATE OR REPLACE FUNCTION substrate.format_last_seen(p_days numeric)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE v_minutes float;
BEGIN
    IF p_days IS NULL THEN RETURN 'Never'; END IF;
    v_minutes := p_days * 1440;
    IF v_minutes < 1     THEN RETURN 'Now';
    ELSIF v_minutes < 60 THEN RETURN round(v_minutes) || 'm';
