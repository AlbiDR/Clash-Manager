CREATE OR REPLACE FUNCTION substrate.shred_clan_members()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_clan_tag TEXT;
    v_recruit_tag TEXT;
BEGIN
    -- Identify the target clan
    v_clan_tag := COALESCE(NEW.clan_tag, (SELECT clan_tag FROM drivers.clans LIMIT 1));

    -- 1. UPSERT participants into universal players registry first to satisfy FKs
    INSERT INTO drivers.players (player_tag, player_name)
    SELECT
        m->>'tag',
        m->>'name'
    FROM jsonb_array_elements(NEW.payload->'items') m
    WHERE (m->>'tag') != v_clan_tag
    ON CONFLICT (player_tag) DO UPDATE SET
        player_name = EXCLUDED.player_name,
        updated_at  = now();

    -- 2. UPSERT current members into drivers.members
    INSERT INTO drivers.members (
        player_tag, player_name, role, exp_level, trophies,
        donations, donations_received, clan_rank, last_seen_at,
        last_ingested_at, is_active, updated_at, current_clan_tag
    )
    SELECT
        m->>'tag',
        m->>'name',
        m->>'role',
        (m->>'expLevel')::INT,
        (m->>'trophies')::INT,
        COALESCE((m->>'donations')::INT, 0),
        COALESCE((m->>'donationsReceived')::INT, 0),
        (m->>'clanRank')::INT,
        (m->>'lastSeen')::TIMESTAMP WITH TIME ZONE,
        now(),
        TRUE,
        now(),
        v_clan_tag
    FROM jsonb_array_elements(NEW.payload->'items') m
    WHERE (m->>'tag') != v_clan_tag
    ON CONFLICT (player_tag) DO UPDATE SET
        player_name          = EXCLUDED.player_name,
        role                 = EXCLUDED.role,
        exp_level            = EXCLUDED.exp_level,
        trophies             = EXCLUDED.trophies,
        donations            = EXCLUDED.donations,
        donations_received   = EXCLUDED.donations_received,
        clan_rank            = EXCLUDED.clan_rank,
        -- Monotonic guard: never allow last_seen_at to move backwards.
        -- The CR API lastSeen field is event-triggered, not polled. A sync may
        -- return an older timestamp than what is already stored (API cache lag).
        -- GREATEST ensures we keep the most recent known activity timestamp.
        last_seen_at         = GREATEST(drivers.members.last_seen_at, EXCLUDED.last_seen_at),
        last_ingested_at     = EXCLUDED.last_ingested_at,
        is_active            = TRUE,
        current_clan_tag     = EXCLUDED.current_clan_tag,
        updated_at           = now();

    -- 3. DEACTIVATE LEAVERS
    UPDATE drivers.members
    SET is_active = FALSE, updated_at = now()
    WHERE is_active = TRUE
      AND current_clan_tag = v_clan_tag
      AND player_tag NOT IN (
          SELECT (elem->>'tag')::TEXT
          FROM jsonb_array_elements(NEW.payload->'items') AS elem
      );

    -- 4. CLEANUP RECRUITS (Harmonization)
    -- If an active member is found in the recruits table, they have joined us.
    -- We delete them from the active recruitment pool and log the event.
    FOR v_recruit_tag IN
        SELECT r.player_tag
        FROM drivers.recruits r
        JOIN jsonb_array_elements(NEW.payload->'items') AS m ON (m->>'tag' = r.player_tag)
    LOOP
        -- Log the transition
        INSERT INTO drivers.recruit_ledger (player_tag, event_type, description)
        VALUES (v_recruit_tag, 'JOINED_US', 'Recruit detected in active roster payload.');

        -- Delete from recruits
        DELETE FROM drivers.recruits WHERE player_tag = v_recruit_tag;
    END LOOP;

    RETURN NEW;
END; $function$;

CREATE OR REPLACE FUNCTION substrate.rotate_recruits()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    limit_val  INT;
    v_benched  INT;
    v_promoted INT;
BEGIN
    INSERT INTO substrate.pipeline_heartbeat (component_id, status, last_triggered_at, last_message)
    VALUES ('RECRUIT_ROTATION', 'RUNNING', NOW(), 'Rotation cycle initiated.')
    ON CONFLICT (component_id) DO UPDATE
    SET status = 'RUNNING', last_triggered_at = EXCLUDED.last_triggered_at, last_message = EXCLUDED.last_message;

    SELECT value::INT INTO limit_val FROM substrate.config WHERE key = 'MAX_ACTIVE_RECRUITS';

    -- FIX: DROP IF EXISTS to handle connection reuse edge cases
    DROP TABLE IF EXISTS elite_tags;
    CREATE TEMP TABLE elite_tags AS
    SELECT player_tag FROM drivers.recruits
    WHERE status != 'ARCHIVED'
    ORDER BY raw_potential_score DESC NULLS LAST
    LIMIT limit_val;

    WITH benched_rows AS (
        UPDATE drivers.recruits
        SET status = 'BENCHED'::drivers.recruit_status
        WHERE status = 'ACTIVE'::drivers.recruit_status
          AND player_tag NOT IN (SELECT player_tag FROM elite_tags)
        RETURNING player_tag
    )
    SELECT count(*) INTO v_benched FROM benched_rows;

    WITH promoted_rows AS (
        UPDATE drivers.recruits
        SET status = 'ACTIVE'::drivers.recruit_status
        WHERE player_tag IN (SELECT player_tag FROM elite_tags)
          AND status != 'ACTIVE'::drivers.recruit_status
        RETURNING player_tag
    )
    SELECT count(*) INTO v_promoted FROM promoted_rows;

    UPDATE substrate.pipeline_heartbeat
    SET status           = 'COMPLETED',
        last_success_at  = NOW(),
        last_message     = 'Rotation successful: ' || v_promoted || ' promoted, ' || v_benched || ' benched.',
        updated_at       = NOW()
    WHERE component_id = 'RECRUIT_ROTATION';

EXCEPTION WHEN OTHERS THEN
    UPDATE substrate.pipeline_heartbeat
    SET status          = 'FAILED',
        last_failure_at = NOW(),
        last_message    = SQLERRM,
        updated_at      = NOW()
    WHERE component_id = 'RECRUIT_ROTATION';
    RAISE;
END;
$function$;

CREATE OR REPLACE FUNCTION substrate.purge_worst_recruits()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'features', 'drivers', 'substrate', 'pg_temp'
AS $function$
DECLARE
    v_count INTEGER;
BEGIN
    -- First, aggressively purge corrupted entries (score 0) older than 12h
    DELETE FROM drivers.recruits
    WHERE raw_potential_score = 0
      AND found_date < NOW() - INTERVAL '12 hours';
    
    GET DIAGNOSTICS v_count = ROW_COUNT;

    -- Second, enforce the 500-recruit cap by score, excluding protected statuses
    WITH to_delete AS (
        SELECT player_tag 
        FROM drivers.recruits
        WHERE status NOT IN ('INVITED', 'ACTIVE') -- Protect high-value leads
        ORDER BY raw_potential_score ASC NULLS FIRST
        OFFSET 500 -- Keep top 500
    )
    DELETE FROM drivers.recruits
    WHERE player_tag IN (SELECT player_tag FROM to_delete);
    
    DECLARE
        v_cap_count INTEGER;
    BEGIN
        GET DIAGNOSTICS v_cap_count = ROW_COUNT;
        v_count := v_count + v_cap_count;
    END;
    
    -- Cleanup orphaned ledger entries
    DELETE FROM drivers.recruit_ledger
    WHERE player_tag NOT IN (SELECT player_tag FROM drivers.recruits)
      AND player_tag NOT IN (SELECT player_tag FROM drivers.members);

    IF v_count > 0 THEN
        INSERT INTO substrate.governance_telemetry (event_type, status, message)
        VALUES ('MAINTENANCE_PURGE', 'INFO', 'Purged ' || v_count || ' drivers.recruits (corrupted or low-score) to maintain pipeline health.');
    END IF;

    RETURN v_count;
END;
$function$;

