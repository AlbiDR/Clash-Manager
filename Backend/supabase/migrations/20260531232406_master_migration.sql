BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_type t
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE t.typname = 'recruit_status' AND n.nspname = 'drivers'
    ) THEN
        CREATE TYPE drivers.recruit_status AS ENUM ('ACTIVE', 'QUEUE', 'ARCHIVED', 'INVITED', 'BENCHED');
