    ) THEN
        CREATE TYPE drivers.recruit_event_type AS ENUM ('DISCOVERED', 'SCORE_THRESHOLD_HIT', 'ACTION_INVITED', 'ACTION_DISCARDED', 'JOINED_US', 'PROMOTED', 'BENCHED', 'ROTATED_OUT', 'ARCHIVED', 'GHOST_DETECTED');
